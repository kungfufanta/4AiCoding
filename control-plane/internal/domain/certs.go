package domain

import (
	"crypto/sha256"
	"crypto/tls"
	"crypto/x509"
	"encoding/hex"
	"encoding/pem"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

// CertStore keeps custom certificates where Traefik's file provider sees
// them. Dir is the dynamic-config directory as sandboxd sees it;
// TraefikDir is the same directory as Traefik sees it (paths inside the
// generated YAML must be valid for Traefik).
type CertStore struct {
	Dir        string
	TraefikDir string
}

// Cert is one stored certificate's public metadata (never the key).
type Cert struct {
	ID        string    `json:"id"`
	Subject   string    `json:"subject"`
	DNSNames  []string  `json:"dns_names"`
	NotBefore time.Time `json:"not_before"`
	NotAfter  time.Time `json:"not_after"`
	Default   bool      `json:"default"`
}

// configFile is the Traefik dynamic config sandboxd owns.
const configFile = "sandboxd-certs.yml"

func (c *CertStore) certDir() string { return filepath.Join(c.Dir, "certs") }

// Enabled reports whether the store has somewhere to write.
func (c *CertStore) Enabled() bool { return c != nil && c.Dir != "" }

// Add validates a PEM certificate chain and key, requires it to cover
// wantHost (e.g. a random preview host under the wildcard) and not be
// expired, stores it, and makes it Traefik's default certificate.
func (c *CertStore) Add(certPEM, keyPEM []byte, wantHosts []string, now time.Time) (*Cert, error) {
	if !c.Enabled() {
		return nil, errors.New("certificate storage is not configured (SANDBOXD_TRAEFIK_DYNAMIC_DIR)")
	}
	pair, err := tls.X509KeyPair(certPEM, keyPEM)
	if err != nil {
		return nil, fmt.Errorf("certificate/key: %v", err)
	}
	leaf, err := x509.ParseCertificate(pair.Certificate[0])
	if err != nil {
		return nil, fmt.Errorf("certificate: %v", err)
	}
	if now.After(leaf.NotAfter) {
		return nil, fmt.Errorf("certificate expired at %s", leaf.NotAfter.Format(time.RFC3339))
	}
	for _, h := range wantHosts {
		if err := leaf.VerifyHostname(h); err != nil {
			return nil, fmt.Errorf("certificate does not cover %s: %v", h, err)
		}
	}
	sum := sha256.Sum256(pair.Certificate[0])
	id := hex.EncodeToString(sum[:8])
	if err := os.MkdirAll(c.certDir(), 0o700); err != nil {
		return nil, err
	}
	if err := writeFile(filepath.Join(c.certDir(), id+".crt"), certPEM, 0o644); err != nil {
		return nil, err
	}
	if err := writeFile(filepath.Join(c.certDir(), id+".key"), keyPEM, 0o600); err != nil {
		return nil, err
	}
	if err := writeFile(filepath.Join(c.certDir(), "default"), []byte(id), 0o644); err != nil {
		return nil, err
	}
	if err := c.render(); err != nil {
		return nil, err
	}
	out := certMeta(id, leaf)
	out.Default = true
	return &out, nil
}

// List returns the stored certificates, newest expiry first.
func (c *CertStore) List() ([]Cert, error) {
	out := []Cert{}
	if !c.Enabled() {
		return out, nil
	}
	ents, err := os.ReadDir(c.certDir())
	if errors.Is(err, os.ErrNotExist) {
		return out, nil
	}
	if err != nil {
		return nil, err
	}
	def := c.defaultID()
	for _, e := range ents {
		id, ok := strings.CutSuffix(e.Name(), ".crt")
		if !ok {
			continue
		}
		b, err := os.ReadFile(filepath.Join(c.certDir(), e.Name()))
		if err != nil {
			return nil, err
		}
		blk, _ := pem.Decode(b)
		if blk == nil {
			continue
		}
		leaf, err := x509.ParseCertificate(blk.Bytes)
		if err != nil {
			continue
		}
		m := certMeta(id, leaf)
		m.Default = id == def
		out = append(out, m)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].NotAfter.After(out[j].NotAfter) })
	return out, nil
}

func (c *CertStore) defaultID() string {
	b, _ := os.ReadFile(filepath.Join(c.certDir(), "default"))
	return strings.TrimSpace(string(b))
}

// render writes the Traefik dynamic config: every stored cert is loaded and
// the default one is the default store's certificate (served for any SNI
// that no other cert matches, i.e. every preview host).
func (c *CertStore) render() error {
	ents, err := os.ReadDir(c.certDir())
	if err != nil {
		return err
	}
	tdir := c.TraefikDir
	if tdir == "" {
		tdir = c.Dir
	}
	var b strings.Builder
	b.WriteString("# Generated by sandboxd (POST /v1/domain/certificates). Do not edit.\ntls:\n  certificates:\n")
	for _, e := range ents {
		if id, ok := strings.CutSuffix(e.Name(), ".crt"); ok {
			fmt.Fprintf(&b, "    - certFile: %s\n      keyFile: %s\n",
				filepath.Join(tdir, "certs", id+".crt"), filepath.Join(tdir, "certs", id+".key"))
		}
	}
	if def := c.defaultID(); def != "" {
		fmt.Fprintf(&b, "  stores:\n    default:\n      defaultCertificate:\n        certFile: %s\n        keyFile: %s\n",
			filepath.Join(tdir, "certs", def+".crt"), filepath.Join(tdir, "certs", def+".key"))
	}
	return writeFile(filepath.Join(c.Dir, configFile), []byte(b.String()), 0o644)
}

func certMeta(id string, leaf *x509.Certificate) Cert {
	names := leaf.DNSNames
	if names == nil {
		names = []string{}
	}
	return Cert{ID: id, Subject: leaf.Subject.CommonName, DNSNames: names,
		NotBefore: leaf.NotBefore.UTC(), NotAfter: leaf.NotAfter.UTC()}
}

// writeFile writes atomically (temp + rename) so Traefik's watcher never
// reads a half-written file.
func writeFile(path string, b []byte, mode os.FileMode) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".tmp-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(b); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(mode); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}
